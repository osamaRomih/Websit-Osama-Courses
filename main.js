/* Language Engine (RTL/LTR Switch) */
function initLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('app_lang', lang);

  const body = document.body;
  const html = document.documentElement;

  if (lang === 'ar') {
    body.setAttribute('dir', 'rtl');
    html.setAttribute('lang', 'ar');
    document.getElementById('lang-text').innerText = 'EN';
  } else {
    body.setAttribute('dir', 'ltr');
    html.setAttribute('lang', 'en');
    document.getElementById('lang-text').innerText = 'عربي';
  }

  // Update all elements with data-i18n
  const elements = document.querySelectorAll('[data-i18n]');
  elements.forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (i18n[lang] && i18n[lang][key]) {
      el.innerText = i18n[lang][key];
    }
  });

  // Update form placeholders
  const nameInput = document.getElementById('student-name');
  const emailInput = document.getElementById('student-email');
  const phoneInput = document.getElementById('student-phone');

  if (nameInput) nameInput.placeholder = lang === 'ar' ? 'مثال: محمد أحمد' : 'e.g. John Doe';
  if (emailInput) emailInput.placeholder = lang === 'ar' ? 'name@example.com' : 'name@example.com';
  if (phoneInput) phoneInput.placeholder = lang === 'ar' ? '01XXXXXXXX' : '+20 10XXXXXXX';
}

function toggleLanguage() {
  const newLang = currentLang === 'ar' ? 'en' : 'ar';
  initLanguage(newLang);
}

/* Theme Engine (Dark/Light Switch) */
function initTheme() {
  document.documentElement.setAttribute('data-theme', currentTheme);
  const themeIcon = document.getElementById('theme-icon');
  if (themeIcon) {
    themeIcon.className = currentTheme === 'dark' ? 'fas fa-sun' : 'fas fa-moon';
  }
}

function toggleTheme() {
  currentTheme = currentTheme === 'dark' ? 'light' : 'dark';
  localStorage.setItem('app_theme', currentTheme);
  initTheme();
}

/* Interactive Particles Canvas */
function initParticles() {
  const canvas = document.getElementById('particles-canvas');
  if (!canvas) return;
  const ctx = canvas.getContext('2d');

  let width = canvas.width = window.innerWidth;
  let height = canvas.height = window.innerHeight;

  window.addEventListener('resize', () => {
    width = canvas.width = window.innerWidth;
    height = canvas.height = window.innerHeight;
  });

  const numParticles = Math.min(Math.floor(width / 20), 65);
  const particles = [];

  for (let i = 0; i < numParticles; i++) {
    particles.push({
      x: Math.random() * width,
      y: Math.random() * height,
      vx: (Math.random() - 0.5) * 0.8,
      vy: (Math.random() - 0.5) * 0.8,
      radius: Math.random() * 2 + 1,
      color: Math.random() > 0.5 ? '#00f2fe' : '#7f00ff'
    });
  }

  function draw() {
    ctx.clearRect(0, 0, width, height);

    for (let i = 0; i < particles.length; i++) {
      let p = particles[i];
      p.x += p.vx;
      p.y += p.vy;

      if (p.x < 0 || p.x > width) p.vx *= -1;
      if (p.y < 0 || p.y > height) p.vy *= -1;

      ctx.beginPath();
      ctx.arc(p.x, p.y, p.radius, 0, Math.PI * 2);
      ctx.fillStyle = p.color;
      ctx.fill();

      for (let j = i + 1; j < particles.length; j++) {
        let p2 = particles[j];
        let dist = Math.hypot(p.x - p2.x, p.y - p2.y);
        if (dist < 120) {
          ctx.beginPath();
          ctx.moveTo(p.x, p.y);
          ctx.lineTo(p2.x, p2.y);
          ctx.strokeStyle = `rgba(0, 242, 254, ${1 - dist / 120 * 0.8})`;
          ctx.lineWidth = 0.5;
          ctx.stroke();
        }
      }
    }
    requestAnimationFrame(draw);
  }

  draw();
}

