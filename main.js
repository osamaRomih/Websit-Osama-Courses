/* Counter Animation for Statistics */
function initStatsCounter() {
  const statNumbers = document.querySelectorAll('.stat-number');
  let animated = false;

  function runCounter() {
    statNumbers.forEach(stat => {
      const target = +stat.getAttribute('data-target');
      const count = +stat.innerText.replace('+', '').replace('%', '');
      const speed = target / 50;

      let current = 0;
      const updateCount = () => {
        current += speed;
        if (current < target) {
          stat.innerText = (stat.getAttribute('data-prefix') || '') + Math.ceil(current) + (stat.getAttribute('data-suffix') || '');
          setTimeout(updateCount, 30);
        } else {
          stat.innerText = (stat.getAttribute('data-prefix') || '') + target + (stat.getAttribute('data-suffix') || '');
        }
      };
      updateCount();
    });
  }

  window.addEventListener('scroll', () => {
    const heroStats = document.querySelector('.hero-stats-row');
    if (heroStats && !animated) {
      const pos = heroStats.getBoundingClientRect().top;
      if (pos < window.innerHeight) {
        animated = true;
        runCounter();
      }
    }
  });
}
