/* JSONPlaceholder Users Modal */
function initUsersModal() {
  const modal = document.getElementById('users-modal');
  const modalContainer = modal?.querySelector('.users-modal-container');
  const openBtn = document.getElementById('open-users-modal');
  const closeBtn = document.getElementById('users-modal-close');
  const retryBtn = document.getElementById('users-retry');
  const loadingState = document.getElementById('users-loading');
  const errorState = document.getElementById('users-error');
  const tableWrap = document.getElementById('users-table-wrap');
  const tableBody = document.getElementById('users-table-body');

  if (!modal || !openBtn || !modalContainer) return;

  let usersLoaded = false;
  let lastFocusedElement = null;

  const setModalState = (isOpen) => {
    modal.classList.toggle('active', isOpen);
    modal.setAttribute('aria-hidden', String(!isOpen));
    document.body.classList.toggle('modal-open', isOpen);

    if (isOpen) {
      lastFocusedElement = document.activeElement;
      modalContainer.focus();
      if (!usersLoaded) loadUsers();
    } else if (lastFocusedElement) {
      lastFocusedElement.focus();
    }
  };

  const createCell = (value, className = '') => {
    const cell = document.createElement('td');
    if (className) cell.className = className;
    cell.textContent = value || '—';
    return cell;
  };

  const renderUsers = (users) => {
    tableBody.replaceChildren();

    users.forEach(user => {
      const row = document.createElement('tr');
      const userCell = document.createElement('td');
      const identity = document.createElement('div');
      const avatar = document.createElement('span');
      const details = document.createElement('span');
      const name = document.createElement('strong');
      const username = document.createElement('small');

      identity.className = 'user-identity';
      avatar.className = 'user-avatar';
      avatar.textContent = user.name.split(' ').slice(0, 2).map(part => part[0]).join('').toUpperCase();
      details.className = 'user-details';
      name.textContent = user.name;
      username.textContent = `@${user.username}`;
      details.append(name, username);
      identity.append(avatar, details);
      userCell.append(identity);

      const emailCell = createCell(user.email, 'user-email');
      const emailLink = document.createElement('a');
      emailLink.href = `mailto:${user.email}`;
      emailLink.textContent = user.email;
      emailCell.replaceChildren(emailLink);

      row.append(
        userCell,
        emailCell,
        createCell(user.phone),
        createCell(user.company?.name),
        createCell(user.address?.city)
      );
      tableBody.append(row);
    });
  };





  function loadUsers() {
    loadingState.hidden = false;
    errorState.hidden = true;
    tableWrap.hidden = true;

    fetch("https://jsonplaceholder.typicode.com/users")
      .then(response => {
        if (!response.ok) throw new Error(`HTTP ${response.status}`);
        return response.json();
      })
      .then(users => {
        console.log(users);
        renderUsers(users);
        usersLoaded = true;
        loadingState.hidden = true;
        tableWrap.hidden = false;
      })
      .catch(error => {
        console.error(error);
        loadingState.hidden = true;
        errorState.hidden = false;
      });
  }

  openBtn.addEventListener('click', () => setModalState(true));
  closeBtn.addEventListener('click', () => setModalState(false));
  retryBtn.addEventListener('click', loadUsers);
  modal.addEventListener('click', (event) => {
    if (event.target === modal) setModalState(false);
  });
  document.addEventListener('keydown', (event) => {
    if (event.key === 'Escape' && modal.classList.contains('active')) {
      setModalState(false);
    }
  });
}

